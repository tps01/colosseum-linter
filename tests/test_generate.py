"""Unit tests for stub rendering and discovery capture."""

from __future__ import annotations

import sys
import types
from pathlib import Path

import pytest

# Extension-shipped package lives under extension/python/
_ROOT = Path(__file__).resolve().parents[1]
_PYTHON_ROOT = _ROOT / "extension" / "python"
if str(_PYTHON_ROOT) not in sys.path:
    sys.path.insert(0, str(_PYTHON_ROOT))

from colosseum_linter.discover import CaptureRegistry, discover_namespaces  # noqa: E402
from colosseum_linter.generate import render_stub, write_stub  # noqa: E402


def test_render_stub_includes_core_and_namespaces() -> None:
    text = render_stub(
        {
            "equipment": "colosseum_equipment.api",
            "io": "colosseum_equipment.io.api",
        },
    )
    assert "AUTO-GENERATED by colosseum-linter" in text
    assert "import colosseum.config as config" in text
    assert "from colosseum.decorators import (" in text
    assert "import colosseum_equipment.api as equipment" in text
    assert "import colosseum_equipment.io.api as io" in text
    # Sorted by namespace name: equipment before io
    assert text.index("as equipment") < text.index("as io")


def test_render_stub_empty_namespaces() -> None:
    text = render_stub({})
    assert "No colosseum.plugins namespaces discovered" in text
    assert "as equipment" not in text


def test_write_stub_creates_pyi(tmp_path: Path) -> None:
    path = write_stub(tmp_path, {"acme": "acme_plugin.api"})
    assert path == tmp_path / "colosseum" / "__init__.pyi"
    assert path.is_file()
    content = path.read_text(encoding="utf-8")
    assert "import acme_plugin.api as acme" in content


def test_capture_registry_records_modules() -> None:
    mod = types.ModuleType("fake_plugin.api")
    reg = CaptureRegistry()
    reg.register_namespace("fake", mod)
    reg.register_config_section(object())
    reg.register_shutdown(lambda: None)
    reg.register_listener("x", lambda *a, **k: None)
    assert reg.namespaces == {"fake": "fake_plugin.api"}


def test_capture_registry_duplicate_warns() -> None:
    a = types.ModuleType("pkg.a")
    b = types.ModuleType("pkg.b")
    reg = CaptureRegistry()
    reg.register_namespace("ns", a)
    reg.register_namespace("ns", b)
    assert reg.namespaces == {"ns": "pkg.a"}
    assert len(reg.warnings) == 1
    assert "already registered" in reg.warnings[0]


def test_discover_with_injected_register() -> None:
    """Simulate a third-party plugin register without real entry points."""

    api = types.ModuleType("third_party.api")

    def register(registry: CaptureRegistry) -> None:
        registry.register_namespace("third", api)

    reg = CaptureRegistry()
    register(reg)
    text = render_stub(reg.namespaces)
    assert "import third_party.api as third" in text


def test_discover_namespaces_tolerates_bad_entry_point(monkeypatch: pytest.MonkeyPatch) -> None:
    class BadEp:
        name = "broken"
        value = "broken:register"

        def load(self) -> object:
            raise RuntimeError("boom")

    class GoodEp:
        name = "ok"
        value = "ok:register"

        def load(self):
            def register(registry: CaptureRegistry) -> None:
                registry.register_namespace("ok", types.ModuleType("ok.api"))

            return register

    monkeypatch.setattr(
        "colosseum_linter.discover.entry_points_for_group",
        lambda group="colosseum.plugins": [BadEp(), GoodEp()],
    )
    capture = discover_namespaces()
    assert capture.namespaces == {"ok": "ok.api"}
    assert any("broken" in w for w in capture.warnings)
